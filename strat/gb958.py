def _dephase(els):
    """叠加元素错半格，避免与基岩符号网格重合。"""
    out = []
    for el in els:
        el = dict(el)
        typ = el.get("type")
        if typ in ("markers", "dots", "shape"):
            # 点阵和矢量图形都支持网格横向相位。
            el.setdefault("stagger", False)
            el.setdefault("xoff", 0.5)
        elif typ == "lines":
            # lines 没有 xoff/stagger；phase 是沿线方向的合法相位。
            el.setdefault("phase", 0.5)
        elif typ == "ell":
            # ell 只支持交错行，不支持 xoff。
            el.setdefault("stagger", False)
        elif typ == "rows":
            # 行式花纹的相位应用在行内图元，而不是 rows 本身。
            el["rows"] = [_dephase(row) for row in (el.get("rows") or [])]
        out.append(el)
    return out


def _sed_spec(name):
    for suf, base, color in SED_BASE:
        if name.endswith(suf):
            prefix = name[: -len(suf)]
            els = [dict(e) for e in base]
            # 层厚变体（灰岩类）
            if suf.endswith("灰岩") and prefix.startswith(("薄层", "页片状")):
                els = [_brk(spacing=1.2 if prefix.startswith("页片状")
                            else 1.6, ratio=3.4)]
                prefix = prefix[2 if prefix.startswith("薄层") else 3:]
            return els + _dephase(_overlays(prefix)), color
    return None, None


def _grain_size(prefix, table):
    for key, val in table:
        if key in prefix:
            return val
    return None


