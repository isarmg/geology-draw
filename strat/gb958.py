class GB958RegistrationError(RuntimeError):
    """GB/T 958 目录无法完整注册。

    ``failures`` 保留每个失败条目的代码、名称和原始异常，
    方便启动日志和测试一次定位全部问题。
    """

    def __init__(self, failures):
        self.failures = tuple(failures)
        details = "\n".join(
            f"  - {code} {name}: {type(exc).__name__}: {exc}"
            for code, name, exc in self.failures
        )
        super().__init__(
            f"GB/T 958 花纹目录有 {len(self.failures)} 项注册失败：\n"
            f"{details}"
        )

