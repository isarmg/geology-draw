def _igneous_spec(name, table):
    for suf, base, color in table:
        if name.endswith(suf):
            prefix = name[: -len(suf)]
            if isinstance(base, str):          # 引用已有内置花纹
                return base, color, prefix
            return [dict(e) for e in base], color, prefix
    return None, None, None


def _pyro_spec(name):
    comp = None
    for c in sorted(PYRO_COMP, key=len, reverse=True):
        if name.startswith(c):
            comp = c
            break
    if comp is None:
        return None, None
    rest = name[len(comp):]
    els = [dict(e) for e in PYRO_COMP[comp]]
    added = set()
    for key, sym in PYRO_CLAST:
        if key in rest and key not in added:
            els += _dephase(sym)
            added.add(key)
        if len(added) >= 3:
            break
    if "熔结" in rest:
        els += [SH("波折线", 1.8, 0.6, 2.4, stagger=False)]
    if rest.startswith("沉") or "沉火山" in rest or "沉集块" in rest \
            or "沉角砾" in rest or "沉凝灰" in rest:
        # 附录 A.2.4 d)：沉火山碎屑岩在花纹中加表示层状的横线（实线）
        els += [LN(0, 2.6)]
    return els, PYRO_COLOR[comp]


def _meta_spec(name):
    for suf, patt, color in META_BASE:
        if name.endswith(suf):
            prefix = name[: -len(suf)]
            if patt is None:
                if suf in ("斜长角闪岩", "角闪岩"):
                    base = [dict(_WAVE),
                            SH("N形", 1.3, 1.7, 2.6, stagger=False),
                            TXT("<", 2.6, 4.2, stagger=False, xoff=0.5)]
                elif suf == "表壳岩":
                    base = [dict(_WAVE), TXT("K", 3.0, 4.0),
                            SH("N形", 1.3, 1.7, 3.0, stagger=False,
                               xoff=0.5)]
                else:
                    base = [dict(_WAVE)]
            else:
                base = patt                     # 已有内置花纹名
            return base, color, prefix
    # 变火山岩/变质碎屑岩
    if name.startswith("变") or name.startswith("变质"):
        inner = name[2 if name.startswith("变质") else 1:]
        for fn in (_sed_spec,):
            els, color = fn(inner)
            if els:
                return ([dict(_WAVE)] + _dephase(els[:2]),
                        color or "#d5cabb", "")
        for table in (LAVA_BASE,):
            els, color, prefix = _igneous_spec(inner, table)
            if els:
                base = L.PATTERNS.get(els).spec if isinstance(els, str) \
                    else els
                return ([dict(_WAVE)] + _dephase(list(base)[:2]),
                        color or "#d5cabb", prefix)
    return None, None, None


