def spec_for(code, name):
    """条目 → (spec 或内置花纹名, 底色)。

    正式 GB/T 958 代码找不到生成规则时抛出 ValueError；只有非目录
    的扩展名称才使用类别缺省点阵。这样标准项的规则回归不会以
    “仍然能渲染”的形式被掩盖。
    """
    cat, _sub = _section(code)
    if cat == "基本花纹":
        sym = BP_SYM.get(name) or BP_SYM.get(
            re.sub(r"[(（][^)）]*[)）]", "", name))
        if sym is None:
            if code in _OFFICIAL_CODES:
                raise ValueError(f"{code} {name}：未找到基本花纹符号")
            sym = [MK(".", 2.0, 1.6)]
        return sym, "#ffffff"
    # 名称去括注后按规则匹配（"灰岩(石灰岩)"→"灰岩"）
    plain = re.sub(r"[(（][^)）]*[)）]", "", name)
    if plain in OVERRIDES:
        return OVERRIDES[plain]
    if plain != name:
        spec, color = _spec_by_rules(code, plain)
        if spec is not None:
            return spec, color
    spec, color = _spec_by_rules(code, name)
    if spec is not None:
        return spec, color
    if code in _OFFICIAL_CODES:
        raise ValueError(f"{code} {name}：未找到国标花纹生成规则")
    # 兜底：类别缺省色 + 中性点阵（保证每条都有图例）
    return [MK(".", 2.0, 1.6)], _FALLBACK_COLOR.get(cat, "#eceae2")


def _spec_by_rules(code, name):
    cat, _sub = _section(code)
    if cat == "沉积岩":
        els, color = _sed_spec(name)
        if els:
            return els, color
    elif cat == "松散堆积物":
        els, color = _loose_spec(name)
        if els:
            return els, color
    elif cat in ("侵入岩", "火山熔岩"):
        table = INTR_BASE if cat == "侵入岩" else LAVA_BASE
        base, color, prefix = _igneous_spec(name, table)
        if base is not None:
            if isinstance(base, str):
                if not prefix:
                    return base, color
                base = [dict(e) for e in L.PATTERNS[base].spec]
            return base + _dephase(_overlays(prefix, budget=2)), color
        # 熔岩表兜底也查侵入表（如熔岩类里的"玢岩"细分）
        base, color, prefix = _igneous_spec(name, INTR_BASE)
        if base is not None and not isinstance(base, str):
            return base + _dephase(_overlays(prefix, budget=2)), color
    elif cat == "火山碎屑岩":
        els, color = _pyro_spec(name)
        if els:
            return els, color
    elif cat == "脉岩":
        els, color = _dyke_spec(name)
        if els:
            return els, color
    elif cat == "变质岩":
        base, color, prefix = _meta_spec(name)
        if base is not None:
            if isinstance(base, str):
                if not prefix:
                    return base, color
                base = [dict(e) for e in L.PATTERNS[base].spec]
            return base + _dephase(_overlays(prefix, budget=2)), color
    elif cat == "蚀变岩":
        els, color = _alter_spec(name)
        if els:
            return els, color
    elif cat == "构造岩":
        if name in TECT:
            return [dict(e) for e in TECT[name]], "#d4cec2"
    elif cat == "混合岩":
        if name in MIGM:
            return [dict(e) for e in MIGM[name]], "#dcc7b4"
    return None, None


