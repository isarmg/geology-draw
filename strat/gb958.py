def SH(shape, w, h, spacing, **kw):
    return {"type": "shape", "shape": shape, "w": w, "h": h,
            "spacing": spacing, **kw}


def MK(marker, spacing, size, **kw):
    return {"type": "markers", "marker": marker, "spacing": spacing,
            "size": size, **kw}


def TXT(s, spacing=2.8, size=4.2, **kw):
    return {"type": "markers", "marker": rf"$\mathrm{{{s}}}$",
            "spacing": spacing, "size": size, **kw}


def LN(angle, spacing, **kw):
    return {"type": "lines", "angle": angle, "spacing": spacing, **kw}


# 稀疏叠加符号的标准网格（附加花纹相对基本花纹错半格）
def _ov(els, spacing=3.0):
    out = []
    for i, el in enumerate(els):
        el = dict(el)
        el.setdefault("spacing", spacing)
        if i == 0:
            el.setdefault("stagger", False)
            el.setdefault("xoff", 0.5)
        out.append(el)
    return out


