_QUAL_KEYS = sorted((k for k, v in QUAL.items() if v is not None),
                    key=len, reverse=True)


def _overlays(prefix, budget=3):
    """把岩石名的修饰前缀解析为叠加符号元素列表（贪心、长词优先）。

    配比按附录 A 表 A.2：QUAL 缺省网格约为“××质”级（附加:基本≈1:2）；
    “含××”更稀疏（1:3），把该组符号间距放大 1.25 倍近似。"""
    out, rest, used = [], prefix, 0
    guard = 0
    while rest and used < budget and guard < 20:
        guard += 1
        # 先按原词匹配（"含磷"等本身就是词条，其间距已按 1:3 设计）；
        # 匹配不上而以"含"开头时，剥掉"含"再匹配并把间距放大 1.25 倍
        hit = next((k for k in _QUAL_KEYS if rest.startswith(k)), None)
        dilute = False
        if hit is None and rest.startswith("含"):
            hit = next((k for k in _QUAL_KEYS if rest[1:].startswith(k)),
                       None)
            if hit is not None:
                dilute = True
                rest = rest[1:]
        if hit is not None:
            for e in QUAL[hit]:
                e = dict(e)
                if dilute and "spacing" in e:
                    e["spacing"] = round(e["spacing"] * 1.25, 2)
                out.append(e)
            rest = rest[len(hit):]
            used += 1
        else:
            rest = rest[1:]     # 未识别的字跳过（如"状""化"或粒级词）
    return out


