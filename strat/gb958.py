def _section(code):
    """代码 → (大类, 小类)。"""
    if code.startswith("RPBP"):
        return "基本花纹", ""
    if code.startswith("RPSE021"):
        return "沉积岩", ""
    if code.startswith("RPSE022"):
        return "松散堆积物", ""
    if code.startswith("RPMM01"):
        return "侵入岩", _SUBSECTS_MM01.get(code[6], "")
    if code.startswith("RPMM02"):
        return "火山熔岩", _SUBSECTS_MM02.get(code[6], "")
    if code.startswith("RPMM03"):
        return "火山碎屑岩", _SUBSECTS_MM03.get(code[6], "")
    if code.startswith("RPMM04"):
        return "脉岩", ""
    if code.startswith("RPMR"):
        num = int(code[6:])
        for lo, hi, name in _META_RANGES:
            if lo <= num <= hi:
                return "变质岩", name
        return "变质岩", ""
    if code.startswith("RPAR"):
        return "蚀变岩", ""
    if code.startswith("RPTC"):
        return "构造岩", ""
    if code.startswith("RPMI"):
        return "混合岩", ""
    return "其他", ""


