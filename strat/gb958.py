GB_NAMES = set()          # 目录注册的岩性名（供常用一览过滤）
_CATALOG = None           # [(大类, [(小类, [(code, name), ...]), ...]), ...]


def catalog():
    """按标准分类组织的目录（惰性构建）。"""
    global _CATALOG
    if _CATALOG is None:
        by = {c: [] for c in CATEGORIES}
        for code, name in ENTRIES:
            cat, sub = _section(code)
            by.setdefault(cat, []).append((sub, code, name))
        _CATALOG = []
        for cat in CATEGORIES:
            subs, order = {}, []
            for sub, code, name in by.get(cat, []):
                if sub not in subs:
                    subs[sub] = []
                    order.append(sub)
                subs[sub].append((code, name))
            _CATALOG.append((cat, [(s, subs[s]) for s in order]))
    return _CATALOG


def register_all():
    """把全部条目注册进花纹/岩性库；重复调用无害。

    所有条目先生成并校验，只有全部成功才提交到全局注册表。
    失败时抛出 GB958RegistrationError，其 failures 包含全部失败项，
    不会留下部分注册状态。返回本次新注册的岩性数。
    """
    pending = []
    failures = []
    seen_codes = set()
    seen_names = set()

    for code, name in ENTRIES:
        cat, _sub = _section(code)
        if code in seen_codes:
            failures.append((code, name, ValueError("目录代码重复")))
            continue
        seen_codes.add(code)
        if cat == "基本花纹":
            # 基本符号不是岩性，但仍预检规则和参数。
            try:
                spec, _color = spec_for(code, name)
                L.normalize_spec(spec, where=f"{code} {name}")
            except Exception as exc:
                failures.append((code, name, exc))
            continue
        if name in seen_names:
            failures.append((code, name, ValueError("非基本花纹名称重复")))
            continue
        seen_names.add(name)

        try:
            spec, color = spec_for(code, name)
            if isinstance(spec, str):
                if spec not in L.PATTERNS:
                    raise ValueError(f"引用的内置花纹“{spec}”不存在")
                pattern = None
            else:
                pattern = L.build_spec_pattern(spec, fixed_layer_rows=True)
            # 已有内置常用岩性优先，不覆盖；但上面仍完整
            # 校验它的国标 spec，避免“因同名而跳过完整性检查”。
            if name not in L.LITHOLOGY:
                pending.append((code, name, color, spec, pattern))
        except Exception as exc:
            failures.append((code, name, exc))

    if failures:
        raise GB958RegistrationError(failures)

    for code, name, color, spec, pattern in pending:
        if isinstance(spec, str):
            pname = spec
        else:
            pname = f"gb:{code}"
            L.PATTERNS[pname] = pattern
        L.LITHOLOGY[name] = (color, pname)
        GB_NAMES.add(name)
        L.SHEET_HIDDEN.add(name)   # 不进"常用岩性一览"，在分类表显示
    return len(pending)


def render_catalog_sheet(category, ncols=4):
    """绘制某一大类的分组图例表（含小类节标题）。"""
    from matplotlib.figure import Figure
    from matplotlib.patches import Polygon

    from . import fonts
    fonts.setup()
    register_all()

    groups = dict(catalog()).get(category)
    if groups is None:
        raise ValueError(f"未知类别“{category}”，可用：" +
                         "、".join(CATEGORIES))

    cell_w, cell_h, head_h = 2.75, 0.82, 0.42
    sw, sh = 0.87, 0.58   # 22×15 mm，与花纹库一览一致
    n_items = sum(len(items) for _s, items in groups)
    nrows = sum(-(-len(items) // ncols) for _s, items in groups)
    n_heads = sum(1 for s, _i in groups if s)
    fig_w = ncols * cell_w + 0.5
    fig_h = 1.0 + nrows * cell_h + n_heads * head_h + 0.3
    fig = Figure(figsize=(fig_w, fig_h), dpi=100)
    fig.patch.set_facecolor("white")
    ax = fig.add_axes([0, 0, 1, 1])
    ax.axis("off")
    ax.set_xlim(0, fig_w)
    ax.set_ylim(0, fig_h)
    fig.text(0.5, 1 - 0.32 / fig_h,
             f"GB/T 958—2015 岩石花纹图例 · {category}（{n_items} 项）",
             ha="center", va="center", fontsize=13, fontweight="bold")

    y = fig_h - 0.85
    for sub, items in groups:
        if sub:
            ax.text(0.3, y - head_h / 2, sub, fontsize=10.5,
                    fontweight="bold", ha="left", va="center",
                    color="#333333")
            ax.plot([0.3, fig_w - 0.3], [y - head_h + 0.06] * 2,
                    color="#999999", lw=0.7)
            y -= head_h
        for i, (code, name) in enumerate(items):
            r, c = divmod(i, ncols)
            x = 0.3 + c * cell_w
            # 行带中心：各行等高、小样垂直居中
            yy = y - (r + 0.5) * cell_h
            verts = [(x, yy - sh / 2), (x + sw, yy - sh / 2),
                     (x + sw, yy + sh / 2), (x, yy + sh / 2)]
            if category == "基本花纹":
                spec, face = spec_for(code, name), "#ffffff"
                spec = spec[0]
                L.paint(ax, verts, None, spec=spec, face=face,
                        spacing=L.BASE_SPACING)
            else:
                L.paint(ax, verts, name, spacing=L.BASE_SPACING)
            ax.add_patch(Polygon(verts, closed=True, facecolor="none",
                                 edgecolor="#333333", lw=0.7, zorder=3))
            # 最长标准名称为 16 个汉字，两行即可完整容纳。旧实现超过
            # 9 字便截断，且目录中不显示标准代码，用户无法可靠区分近似项。
            name_lines = [name[index:index + 9]
                          for index in range(0, len(name), 9)] or [""]
            label = "\n".join(name_lines + [code])
            ax.text(x + sw + 0.08, yy, label, fontsize=7.1,
                    ha="left", va="center", linespacing=1.05)
        y -= -(-len(items) // ncols) * cell_h
    return fig
